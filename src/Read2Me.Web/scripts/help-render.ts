/**
 * The pure half of `bun run help`: one markdown help file → `{ title, html }`, and the entries →
 * the text of `src/app/help/help.generated.ts`. `help.ts` does the file system; this is what
 * `help.spec.ts` exercises.
 */

export interface HelpEntry {
  title: string;
  html: string;
}

const RENDER_OPTIONS = { tagFilter: true, noHtmlBlocks: true, noHtmlSpans: true } as const;

/** The step's help page needs a `# Title` first line; anything else is a lint failure. */
export function renderHelp(source: string, file: string): HelpEntry {
  const fail = (reason: string): never => {
    throw new Error(`${file}: ${reason}`);
  };

  const lines = source.replace(/^﻿/, '').split(/\r?\n/);
  const heading = lines[0] ?? '';
  const match = /^# (.+?)\s*$/.exec(heading);
  if (!match) fail('must start with a `# Title` line');
  const title = match![1]!;
  if (source.includes('![')) fail('holds an image (`![`); help text has none');

  const body = lines.slice(1).join('\n').trimStart();
  let html = Bun.markdown.html(body, RENDER_OPTIONS);

  // Every anchor Bun emits starts `<a href="…"`; a title follows as a further attribute.
  html = html.replace(/<a href="([^"]*)"([^>]*)>/g, (_, href: string, rest: string) => {
    const lower = href.trim().toLowerCase();
    if (lower.startsWith('javascript:')) fail(`unsafe javascript: link (${href})`);
    if (lower.startsWith('data:')) fail(`unsafe data: link (${href})`);
    if (lower.startsWith('/app'))
      fail(`links into the app (${href}); name the control in prose instead`);
    if (!/^https?:\/\//.test(lower)) {
      fail(`relative link (${href}); help links are absolute https:// URLs only`);
    }
    return `<a href="${href}"${rest} target="_blank" rel="noopener">`;
  });
  if (/<a\s(?![^>]*\brel="noopener")/i.test(html)) fail('an anchor escaped the link lint');

  if (/<script/i.test(html)) fail('rendered output holds a <script tag');
  for (const [tag] of html.matchAll(/<[a-z][^>]*>/gi)) {
    if (/\son[a-z]+=/i.test(tag)) fail(`rendered output holds an on*= handler attribute (${tag})`);
  }
  if (/<h1[\s>]/.test(html)) fail('the body has a second `#` heading; body headings start at `##`');

  // The partial renders the title as its <h2>, so body headings sit one level below it.
  html = html.replace(/<(\/?)h([2-5])>/g, (_, slash: string, level: string) => {
    return `<${slash}h${Number(level) + 1}>`;
  });

  return { title, html };
}

/** The committed module's source text: entries in the order given, keyed by step id. */
export function helpModuleSource(entries: Record<string, HelpEntry>): string {
  const body = Object.entries(entries)
    .map(
      ([id, entry]) =>
        `  ${id}: {\n    title: ${quote(entry.title)},\n    html: ${JSON.stringify(entry.html)},\n  },`,
    )
    .join('\n');
  return [
    '// generated by scripts/help.ts from docs/guide/*.md — do not edit; run `bun run help`.',
    "import type { PipelineStepId } from '@app/api/dtos';",
    '',
    'export interface HelpEntry {',
    '  title: string;',
    '  html: string;',
    '}',
    '',
    'export const HELP = {',
    body,
    '} as const satisfies Record<PipelineStepId, HelpEntry>;',
    '',
  ].join('\n');
}

function quote(text: string): string {
  return `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}
