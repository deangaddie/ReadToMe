import { describe, expect, it } from 'bun:test';
import { helpModuleSource, renderHelp } from './help-render';

const FILE = 'docs/guide/import.md';

describe('renderHelp', () => {
  it('takes the h1 as the title and leaves it out of the body', () => {
    const entry = renderHelp(
      '# Import the book\n\nWhat this step is for.\n\n## How\n\nDrop a file.\n',
      FILE,
    );
    expect(entry.title).toBe('Import the book');
    expect(entry.html).not.toContain('<h1');
    expect(entry.html).toContain('<p>What this step is for.</p>');
  });

  it('demotes body headings one level, below the title the partial renders as h2', () => {
    const entry = renderHelp('# T\n\n## How\n\n### Detail\n', FILE);
    expect(entry.html).toContain('<h3>How</h3>');
    expect(entry.html).toContain('<h4>Detail</h4>');
    expect(entry.html).not.toContain('<h2');
  });

  it('rewrites an external link to open in a new tab without a referrer handle', () => {
    const entry = renderHelp('# T\n\nSee [the docs](https://example.com/a).\n', FILE);
    expect(entry.html).toContain(
      '<a href="https://example.com/a" target="_blank" rel="noopener">the docs</a>',
    );
  });

  it('lints and rewrites a link that carries a title too', () => {
    expect(() => renderHelp('# T\n\n[x](javascript:alert(1) "t")\n', FILE)).toThrow('javascript:');
    expect(() => renderHelp('# T\n\n[x](/app/projects "t")\n', FILE)).toThrow('/app');
    const entry = renderHelp('# T\n\n[x](https://example.com/a "t")\n', FILE);
    expect(entry.html).toContain(
      '<a href="https://example.com/a" title="t" target="_blank" rel="noopener">x</a>',
    );
  });

  it('allows only http(s) destinations', () => {
    expect(() => renderHelp('# T\n\n[x](mailto:a@b.c)\n', FILE)).toThrow('https://');
  });

  it('escapes raw HTML instead of passing it through', () => {
    const entry = renderHelp('# T\n\n<b onclick="x()">hi</b>\n\n<div>block</div>\n', FILE);
    expect(entry.html).not.toContain('<b');
    expect(entry.html).not.toContain('<div>');
    expect(entry.html).toContain('&lt;b');
  });

  it.each([
    ['a missing h1', 'Just a paragraph.\n', 'must start with a `# Title` line'],
    ['a javascript: href', '# T\n\n[x](javascript:alert(1))\n', 'javascript:'],
    ['a data: href', '# T\n\n[x](data:text/html,hi)\n', 'data:'],
    ['a relative link', '# T\n\n[x](../other.md)\n', 'relative'],
    ['an /app link', '# T\n\n[x](/app/projects)\n', '/app'],
    ['an image', '# T\n\n![alt](https://example.com/i.png)\n', 'image'],
  ])('fails on %s', (_name, source, reason) => {
    expect(() => renderHelp(source, FILE)).toThrow(reason);
  });

  it('names the file in the failure', () => {
    expect(() => renderHelp('no title\n', FILE)).toThrow(FILE);
  });
});

describe('helpModuleSource', () => {
  it('emits one const keyed by step id that satisfies the PipelineStepId record', () => {
    const text = helpModuleSource({
      import: { title: 'Import', html: '<p>a</p>\n' },
      export: { title: 'Export', html: '<p>b "quoted"</p>\n' },
    });
    expect(text).toContain('export const HELP = {');
    expect(text).toContain('satisfies Record<PipelineStepId, HelpEntry>');
    expect(text).toContain('import: {');
    expect(text).toContain(`title: 'Export'`);
    expect(text).toContain(JSON.stringify('<p>b "quoted"</p>\n'));
    expect(text).toContain('generated by scripts/help.ts');
  });
});
